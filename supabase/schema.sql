-- Restaurante Fahiteiro: schema inicial para Supabase
-- Executa este ficheiro no SQL Editor do teu projecto Supabase.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  role text not null default 'editor' check (role in ('admin','editor'))
);
create table if not exists public.site_content (
  id integer primary key default 1 check (id = 1),
  brand_name text not null default 'FAHITEIRO',
  logo_url text,
  hero_eyebrow text default 'Uma experiência à mesa',
  hero_title text default 'Sabores que aproximam.',
  hero_text text default 'Há refeições que se tornam memórias. No Restaurante Fahiteiro, cada encontro é uma oportunidade para partilhar bons momentos à mesa, em Huambo.',
  hero_image_url text,
  menu_title text default 'Escolha o seu próximo momento favorito.',
  menu_text text default 'Consulte directamente o restaurante para confirmar as opções disponíveis.',
  menu_image_url text,
  address_text text default 'Huambo, Cidade Alta, Angola. Referência no mapa: 6PCP+XQ4, Huambo.',
  updated_at timestamptz not null default now()
);
create table if not exists public.menu_items (
  id bigint generated by default as identity primary key,
  name text not null,
  description text not null default '',
  price_kz numeric(12,2),
  active boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);
insert into public.site_content (id) values (1) on conflict (id) do nothing;
alter table public.profiles enable row level security;
alter table public.site_content enable row level security;
alter table public.menu_items enable row level security;
-- Each signed-in user can read only their own profile.
create policy "profile read own" on public.profiles for select to authenticated using (id = auth.uid());
-- Public website can read published content.
create policy "public read site content" on public.site_content for select to anon, authenticated using (true);
create policy "admin update site content" on public.site_content for update to authenticated using (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin')) with check (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'));
create policy "admin insert site content" on public.site_content for insert to authenticated with check (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'));
create policy "public read active menu" on public.menu_items for select to anon, authenticated using (active = true or exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'));
create policy "admin insert menu" on public.menu_items for insert to authenticated with check (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'));
create policy "admin update menu" on public.menu_items for update to authenticated using (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin')) with check (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'));
create policy "admin delete menu" on public.menu_items for delete to authenticated using (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'));
-- Storage: public read, admin upload/update/delete.
insert into storage.buckets (id,name,public) values ('fahiteiro-images','fahiteiro-images',true) on conflict (id) do nothing;
create policy "public read Fahiteiro images" on storage.objects for select to anon, authenticated using (bucket_id = 'fahiteiro-images');
create policy "admin upload Fahiteiro images" on storage.objects for insert to authenticated with check (bucket_id = 'fahiteiro-images' and exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'));
create policy "admin update Fahiteiro images" on storage.objects for update to authenticated using (bucket_id = 'fahiteiro-images' and exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin')) with check (bucket_id = 'fahiteiro-images' and exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'));
create policy "admin delete Fahiteiro images" on storage.objects for delete to authenticated using (bucket_id = 'fahiteiro-images' and exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'));
